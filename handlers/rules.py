# ─── КЛАВІАТУРИ ──────────────────────────────────────────────────────────────

def games_menu_kb():
    """Верхнее меню — выбор игры."""
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🧠 Мозгобойня",   callback_data="rules_game_mozgoboynya")],
        [InlineKeyboardButton(text="🎵 Туц Туц QUIZ", callback_data="rules_game_tuc_tuc")],
        [InlineKeyboardButton(text="🎮 Квизмашина",   callback_data="rules_game_kvizmashina")],
    ])


def sections_menu_kb(game: str):
    """Меню разделов внутри игры (общие правила / бланки / туры)."""
    sections = RULES[game]["sections"]
    buttons = [
        [InlineKeyboardButton(text=info["title"], callback_data=f"rules_sec_{game}|{key}")]
        for key, info in sections.items()
    ]
    buttons.append([InlineKeyboardButton(text="◀️ К выбору игры", callback_data="rules_menu")])
    return InlineKeyboardMarkup(inline_keyboard=buttons)


def page_kb(game: str, section: str, page: int, total: int):
    buttons = []
    nav = []
    if page > 0:
        nav.append(InlineKeyboardButton(text="◀️ Назад", callback_data=f"rules_page_{game}|{section}|{page - 1}"))
    if page < total - 1:
        nav.append(InlineKeyboardButton(text="Далее ▶️", callback_data=f"rules_page_{game}|{section}|{page + 1}"))
    if nav:
        buttons.append(nav)
    buttons.append([InlineKeyboardButton(text="📋 К разделам", callback_data=f"rules_game_{game}")])
    return InlineKeyboardMarkup(inline_keyboard=buttons)


# ─── ХЕНДЛЕРИ ────────────────────────────────────────────────────────────────

@router.message(F.text == "📖 Правила")
async def show_rules_menu(message: Message):
    await message.answer(
        "📖 *Правила игр*\n\nВыбери игру:",
        reply_markup=games_menu_kb(),
        parse_mode="Markdown"
    )


@router.callback_query(F.data == "rules_menu")
async def rules_back_to_menu(callback: CallbackQuery):
    await callback.message.edit_text(
        "📖 *Правила игр*\n\nВыбери игру:",
        reply_markup=games_menu_kb(),
        parse_mode="Markdown"
    )
    await callback.answer()


@router.callback_query(F.data == "rules_close")
async def rules_close(callback: CallbackQuery):
    await callback.message.delete()
    await callback.answer()


@router.callback_query(F.data.startswith("rules_game_"))
async def show_sections_menu(callback: CallbackQuery):
    game = callback.data.replace("rules_game_", "")

    if game not in RULES:
        await callback.answer("Игра не найдена.")
        return

    await callback.message.edit_text(
        f"{RULES[game]['title']}\n\nВыбери раздел:",
        reply_markup=sections_menu_kb(game),
        parse_mode="Markdown"
    )
    await callback.answer()


@router.callback_query(F.data.startswith("rules_sec_"))
async def show_section_first_page(callback: CallbackQuery):
    # rules_sec_GAME|SECTION
    payload = callback.data.replace("rules_sec_", "")
    parts = payload.split("|")
    if len(parts) != 2:
        await callback.answer()
        return

    game, section = parts
    await render_page(callback, game, section, 0)


@router.callback_query(F.data.startswith("rules_page_"))
async def show_page(callback: CallbackQuery):
    # rules_page_GAME|SECTION|PAGE
    payload = callback.data.replace("rules_page_", "")
    parts = payload.split("|")
    if len(parts) != 3 or not parts[2].isdigit():
        await callback.answer()
        return

    game, section, page = parts[0], parts[1], int(parts[2])
    await render_page(callback, game, section, page)


async def render_page(callback: CallbackQuery, game: str, section: str, page: int):
    if game not in RULES or section not in RULES[game]["sections"]:
        await callback.answer("Раздел не найден.")
        return

    pages = RULES[game]["sections"][section]["pages"]
    total = len(pages)
    page = max(0, min(page, total - 1))

    text = pages[page]
    if total > 1:
        text += f"\n\n_Страница {page + 1} из {total}_"

    await callback.message.edit_text(
        text,
        reply_markup=page_kb(game, section, page, total),
        parse_mode="Markdown"
    )
    await callback.answer()
